    done <<< "$baseline"

    local i
    if (( ${#new[@]} )); then
        printf '%s%sNew problems%s — not in test/known-issues.txt:\n\n' "$RED" "$BOLD" "$NC"
        for id in "${new[@]}"; do
            for i in "${!FINDING_IDS[@]}"; do
