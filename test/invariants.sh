FINDING_IDS=()
FINDING_MESSAGES=()

report() {
    FINDING_IDS+=("$1")
    FINDING_MESSAGES+=("$2")
}

env_keys() {
    grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$RELEASE_ENV" | tr -d '='
}

keys_the_installer_generates() {
    grep -o 'GENERATED_SECRET_KEYS=([^)]*)' "$REPO_ROOT/bin/ut-install" 2>/dev/null \
        | sed 's/.*(//; s/)//' | tr ' ' '\n'
    printf 'MONGODB_USERNAME\nMONGODB_PASSWORD\n'
}

keys_a_machine_will_have() {
    { env_keys; keys_the_installer_generates; } | sort -u
}

env_raw_value() {
    local key=$1 line
    line=$(grep -m1 -E "^${key}=" "$RELEASE_ENV" 2>/dev/null) || return 1
    line=${line#*=}
    line=${line%\"}; line=${line#\"}
    line=${line%\'}; line=${line#\'}
    printf '%s' "$line"
}

# ut-get --from adds what it finds in the folder once it has refused, with
# --browser, every option of the operator's own: ut-setup has to read each one.
check_ut_setup_reads_what_ut_get_hands_it() {
    local option
    while read -r option; do
        [[ -n "$option" ]] || continue
        grep -qF "flags.String(\"${option#--}\"" "$REPO_ROOT/cmd/ut-setup/main.go" \
            || report "handover-unread:${option}" \
                "ut-get --from hands ${option} to ut-setup, which does not read it: the page never opens"
    done <<< "$(sed -n '/^main() {/,/^}/p' "$REPO_ROOT/bin/ut-get" | grep -oE 'INSTALL_ARGUMENTS\+=\(--[a-z-]+' | sed 's/.*(//')"
}

check_plaintext_secrets() {
    local key value
    for key in "${SENSITIVE_KEYS[@]}"; do
        value=$(env_raw_value "$key" 2>/dev/null) || continue
        [[ -z "$value" ]] && continue
        report "plaintext-secret:${key}" \
            "${key} ships a value in release.env — every deployment that follows the guide reuses it"
    done
}

# Wider than SENSITIVE_KEYS on purpose: compose.yaml reads HF_TOKEN and falls
# back to HF_API_TOKEN, which that nominative list never mentions.
check_release_env_ships_no_secret() {
    [[ -f "$RELEASE_ENV" ]] || return 0
    local key name exempt sensitive
    while read -r key; do
        [[ -n "$key" ]] || continue
        exempt=0
        for name in "${NOT_SECRETS_DESPITE_THE_NAME[@]}"; do
            if [[ "$key" == "$name" ]]; then exempt=1; fi
        done
        (( exempt == 0 )) || continue
        sensitive=0
        for name in "${SENSITIVE_KEYS[@]}"; do
            if [[ "$key" == "$name" ]]; then sensitive=1; fi
        done
        case "$key" in
            *_SECRET|*_TOKEN|*_PASSWORD|*_KEY|*_KEY_ID) sensitive=1 ;;
        esac
        (( sensitive )) || continue
        report "secret-in-release-env:${key}" \
            "${key} is declared in release.env, which the package ships world-readable — a secret belongs in local.env, generated by ut-install"
    done <<< "$(grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$RELEASE_ENV" | tr -d '=')"
}

# release.env is not the only place a secret can ship from: a compose file
# writing ${JWT_SECRET:-something} carries that something into every deployment
# whose .env leaves the variable out. MONGODB_PASSWORD defaulted to 12345678
# here, which emptying release.env would not have touched.
check_compose_declares_no_secret_default() {
    local key default
    for key in "${SENSITIVE_KEYS[@]}"; do
        default=$(grep -ohE "\\\$\{${key}:-[^\\\${}]+\}" "${COMPOSE_FILES[@]}" 2>/dev/null | head -1) || continue
        [[ -n "$default" ]] || continue
        report "compose-secret-default:${key}" \
            "a compose file falls back to a value for ${key} (${default}) — it ships from here too"
    done
}

seconds_in_duration() {
    local duration=$1 number=${1%[a-z]}
    case "$duration" in
        *h) printf '%s' $(( number * 3600 )) ;;
        *m) printf '%s' $(( number * 60 )) ;;
        *s) printf '%s' "$number" ;;
        *)  printf '%s' "$duration" ;;
    esac
}

# Each start_period is reported against the service it belongs to, so two
# services sharing one value are two findings, not one.
#
# Only services ut-install waits for are bound by its budget. An inference
# engine is left loading in the background, so its start_period answers to its
# own health check and not to the installer. Without this distinction the check
# would stay green for a reason that no longer holds.
check_no_service_starts_slower_than_the_installer_waits() {
    local budget entry line service role period seconds
    budget=$(grep -m1 -oE 'HEALTH_TIMEOUT="\$\{UT_HEALTH_TIMEOUT:-[0-9]+' "$REPO_ROOT/bin/ut-install" 2>/dev/null \
        | grep -oE '[0-9]+$') || return 0
    [[ -n "$budget" ]] || return 0
    service=""
    role=""
    while IFS= read -r line; do
        entry=${line%"${line##*[![:space:]]}"}
        case "$entry" in
            "  "[a-z]*":")
                service=${entry#  }; service=${service%:}; role=""
                ;;
            *ut.role:*)
                role=$(printf '%s' "$entry" | sed 's/.*ut\.role:[[:space:]]*//; s/"//g')
                ;;
            *start_period:*)
                [[ "$role" != "inference" ]] || continue
                period=$(printf '%s' "$entry" | grep -oE '[0-9]+[hms]') || continue
                [[ -n "$period" ]] || continue
                seconds=$(seconds_in_duration "$period")
                (( seconds > budget )) || continue
                report "start-period-outlasts-the-install:${service:-unknown}" \
                    "${service:-a service} declares start_period ${period}, longer than the $(( budget / 60 )) minutes ut-install waits — the install gives up on a service that was never going to be ready in time"
                ;;
        esac
    done < "$REPO_ROOT/compose.yaml"
}

SERVICE_ROLES="control-plane backup inference metrics"

judge_one_service_role() {
    local service=$1 role=$2
    [[ -n "$service" ]] || return 0
    if [[ -z "$role" ]]; then
        report "service-without-a-role:${service}" \
            "${service} declares no ut.role label — ut-install cannot tell whether to wait for it or let it start in the background, so it waits, and the install is as long as its slowest service"
        return 0
    fi
    case " ${SERVICE_ROLES} " in
        *" ${role} "*) return 0 ;;
    esac
    report "service-with-an-unknown-role:${service}" \
        "${service} declares ut.role ${role}, which is none of: ${SERVICE_ROLES} — ut-install would not know what to do with it"
}

# The role lives beside the service it describes. A list inside ut-install would
# drift the first time a service is added, and nothing would say so.
check_every_service_declares_its_role() {
    local line entry in_services=false service="" role=""
    while IFS= read -r line; do
        # compose.yaml carries trailing spaces on some service lines; matching
        # on the raw line silently skips those services.
        entry=${line%"${line##*[![:space:]]}"}
        case "$entry" in
            "services:")
                in_services=true
                continue
                ;;
            [a-z]*:*)
                if $in_services; then
                    judge_one_service_role "$service" "$role"
                fi
                in_services=false
                service=""
                role=""
                continue
                ;;
        esac
        $in_services || continue
        case "$entry" in
            "  "[a-z]*":")
                judge_one_service_role "$service" "$role"
                service=${entry#  }
                service=${service%:}
                role=""
                ;;
            *ut.role:*)
                role=$(printf '%s' "$line" | sed 's/.*ut\.role:[[:space:]]*//; s/"//g; s/[[:space:]]*$//')
                ;;
        esac
    done < "$REPO_ROOT/compose.yaml"
    if $in_services; then
        judge_one_service_role "$service" "$role"
    fi
}

judge_one_service_health() {
    local service=$1 has_healthcheck=$2
    [[ -n "$service" ]] || return 0
    $has_healthcheck && return 0
    report "service-without-a-healthcheck:${service}" \
        "${service} declares no healthcheck — ut-install and ut-status count it as serving for as long as its process runs, even once it no longer does its work"
}

# Docker only knows that a process runs. The healthcheck is what tells ut-install,
# ut-status and the usage report that the service still does its job.
check_every_service_declares_a_healthcheck() {
    local line entry in_services=false service="" has_healthcheck=false
    while IFS= read -r line; do
        entry=${line%"${line##*[![:space:]]}"}
        case "$entry" in
            "services:")
                in_services=true
                continue
                ;;
            [a-z]*:*)
                if $in_services; then
                    judge_one_service_health "$service" "$has_healthcheck"
                fi
                in_services=false
                service=""
                has_healthcheck=false
                continue
                ;;
        esac
        $in_services || continue
        case "$entry" in
            "  "[a-z]*":")
                judge_one_service_health "$service" "$has_healthcheck"
                service=${entry#  }
                service=${service%:}
                has_healthcheck=false
                ;;
            "    healthcheck:")
                has_healthcheck=true
                ;;
        esac
    done < "$REPO_ROOT/compose.yaml"
    if $in_services; then
        judge_one_service_health "$service" "$has_healthcheck"
    fi
}

judge_one_gateway() {
    local service=$1 hosts_the_gateway=$2 trusts_the_builder=$3
    [[ -n "$service" ]] || return 0
    $hosts_the_gateway || return 0
    $trusts_the_builder && return 0
    report "gateway-does-not-trust-the-app-builder:${service}" \
        "${service} serves the LLM gateway without GATEWAY_TRUSTED_PROXY_KEYS falling back to the app builder's key — all builder users share one rate limit, and the builder's calls are counted as plain API use"
}

# The app builder calls the gateway with one key for all its users. Only a key the
# gateway trusts may name the person behind a call, which is what gives each of
# them a rate limit of their own.
check_the_gateway_trusts_the_app_builder_key() {
    local line entry in_services=false block="" hosts=false trusts=false
    while IFS= read -r line; do
        entry=${line%"${line##*[![:space:]]}"}
        case "$entry" in
            "services:"|x-*:*|[a-z]*:*)
                judge_one_gateway "$block" "$hosts" "$trusts"
                hosts=false
                trusts=false
                block=""
                in_services=false
                case "$entry" in
                    "services:") in_services=true ;;
                    x-*) block=${entry%%:*} ;;
                esac
                continue
                ;;
        esac
        if $in_services && [[ "$entry" == "  "[a-z]*":" ]]; then
            judge_one_gateway "$block" "$hosts" "$trusts"
            block=${entry#  }
            block=${block%:}
            hosts=false
            trusts=false
            continue
        fi
        case "$entry" in
            *"GATEWAY_RPM_PER_KEY:"*)
                hosts=true
                ;;
            *'GATEWAY_TRUSTED_PROXY_KEYS: ${GATEWAY_TRUSTED_PROXY_KEYS:-${APP_BUILDER_GATEWAY_API_KEY:-}}')
                trusts=true
                ;;
        esac
    done < "$REPO_ROOT/compose.yaml"
    judge_one_gateway "$block" "$hosts" "$trusts"
}

# A backup deferred to a clock time cannot answer a health check that asks for a
# recent archive: the service stays unhealthy until that hour comes round.
check_the_first_backup_is_not_deferred_to_a_clock_time() {
    local begin
    begin=$(grep -m1 -oE 'DB01_BACKUP_BEGIN: "?\$\{BACKUP_BEGIN:-[^}]*\}"?' "$REPO_ROOT/compose.yaml" 2>/dev/null \
        | sed 's/.*:-//; s/}"*$//') || return 0
    [[ -n "$begin" ]] || return 0
    case "$begin" in
        +*) return 0 ;;
    esac
    report "first-backup-deferred:${begin}" \
        "the database backup defaults to ${begin}, a time of day: nothing is backed up before it comes, and the health check that looks for an archive cannot pass until then"
}

# A setting nothing interpolates reaches nothing. No compose file declares an
# env_file, so a value that is neither a render-time substitution nor an entry in
# an environment: block cannot travel to a container — whatever the image's code
# does with the name. Measured on 2026-09-21: release.env read
# AGENT_MAX_OUTPUT_TOKENS=24576 while the App Builder received 8192, thirty lines
# above under another name.
SETTINGS_READ_OUTSIDE_THE_STACK=(
    COMPOSE_FILE COMPOSE_PROFILES COMPOSE_PROJECT_NAME APP_BUILDER_DOCKER
    UT_RELEASE_VERSION UT_RELEASE_BUILT_AT
    ARBITER_HOLD_RELEASE ARBITER_HOLD_SHA256_AMD64 ARBITER_HOLD_SHA256_ARM64
)

check_every_setting_reaches_something() {
    local key name exempt interpolated
    # The Caddyfile spells it {$VAR} and compose ${VAR}, and the overlays count
    # too: a setting used only by compose.compute.yaml is not dead.
    interpolated=$( {
        grep -ohE '\$\{[A-Za-z_][A-Za-z0-9_]*' "$REPO_ROOT"/compose*.yaml 2>/dev/null | tr -d '${'
        grep -ohE '\{\$[A-Za-z_][A-Za-z0-9_]*' "$REPO_ROOT/Caddyfile" "$REPO_ROOT"/caddy/*.caddy 2>/dev/null | tr -d '{$'
    } | sort -u )

    while read -r key; do
        [[ -n "$key" ]] || continue
        exempt=0
        for name in "${SETTINGS_READ_OUTSIDE_THE_STACK[@]}"; do
            [[ "$key" == "$name" ]] && exempt=1
        done
        (( exempt == 0 )) || continue
        grep -qx "$key" <<< "$interpolated" && continue
        report "setting-reaches-nothing:${key}" \
            "release.env declares ${key} and nothing interpolates it — the value cannot travel to any container"
    done <<< "$(env_keys)"
}

service_networks() {
    local files=("$@")
    (( ${#files[@]} )) || files=("$REPO_ROOT"/compose*.yaml)
    awk '/^services:/ { inside = 1; next }
         inside && /^[^[:space:]#]/ { inside = 0 }
         inside && /^  [a-z][a-z0-9-]*:$/ { service = $1; sub(/:$/, "", service); listing = 0; next }
         inside && /^    networks:/ { listing = 1; next }
         listing && /^    [^ ]/ { listing = 0 }
         listing && /^      - / { network = $2; print service, network; next }
         listing && /^      [a-z][a-z0-9-]*:/ { network = $1; sub(/:.*/, "", network); print service, network }' \
        "${files[@]}"
}

internal_networks() {
    awk '/^networks:/ { inside = 1; next }
         inside && /^[^[:space:]#]/ { inside = 0 }
         inside && /^  [a-z][a-z0-9-]*:/ { network = $1; sub(/:.*/, "", network); next }
         inside && /^    internal:[[:space:]]*true/ { print network }' "$@"
}

# files-backup reads every document: with the relay's overlay, its only way out
# is the relay, which sends to the very host files-backup resolves to it.
check_the_backup_leaves_through_its_relay_alone() {
    local overlay="$REPO_ROOT/compose.backup-relay.yaml" internal service network
    [[ -f "$overlay" ]] || return 0
    internal=$(internal_networks "$overlay" "$REPO_ROOT/compose.yaml")
    while read -r service network; do
        [[ "$service" == files-backup ]] || continue
        grep -qx "$network" <<< "$internal" && continue
        report "backup-reaches-out-past-its-relay:${network}" \
            "files-backup joins ${network} in compose.backup-relay.yaml, a network with a way out: the service that reads every document reaches more than the backup's destination"
    done <<< "$(service_networks "$overlay")"
    grep -qF -- '- TCP:${BACKUP_RELAY_HOST:-' "$overlay" && grep -qF -- '- "${BACKUP_RELAY_HOST:-' "$overlay" && return 0
    report "backup-relay-sends-elsewhere" \
        "the relay in compose.backup-relay.yaml does not send to BACKUP_RELAY_HOST, the name files-backup resolves to it: the backup goes somewhere it did not ask for"
}

APPS_DOCKER_OVERLAY="$REPO_ROOT/compose.appbuilder-nested.yaml"
APPS_DOCKER_SETUP="$REPO_ROOT/bin/ut-install.d/app-builder-docker.sh"

apps_docker_service() {
    awk '/^  app-builder-docker:$/ { on = 1; next } on && /^  [^ ]/ { on = 0 } on' "$APPS_DOCKER_OVERLAY"
}

# The image's entrypoint adds tcp://0.0.0.0:2375 unless dockerd is given its own
# arguments: a listener every app on its networks would drive.
check_the_apps_docker_listens_on_its_socket_alone() {
    [[ -f "$APPS_DOCKER_OVERLAY" ]] || return 0
    grep -qF 'command: ["dockerd", "--host=unix:///run/app-builder-docker/docker.sock"]' <<< "$(apps_docker_service)" \
        && ! grep -qE 'tcp://|DOCKER_TLS' "$APPS_DOCKER_OVERLAY" "$APPS_DOCKER_SETUP" && return 0
    report "apps-docker-listens-beyond-its-socket" \
        "the App Builder's Docker in compose.appbuilder-nested.yaml listens elsewhere than its Unix socket: any app it runs could drive it, and reach every other one"
}

check_the_host_docker_socket_stays_in_the_way_back() {
    local file
    for file in "$REPO_ROOT"/compose*.yaml; do
        [[ "${file##*/}" == compose.appbuilder-on-host.yaml ]] && continue
        grep -qE '^[[:space:]]+- "?/var/run/docker\.sock' "$file" || continue
        report "docker-socket-mounted-by:${file##*/}" \
            "${file##*/} mounts this machine's Docker socket: whatever runs there is root on the box. Only compose.appbuilder-on-host.yaml, the App Builder's way back, may"
    done
}

check_the_apps_docker_stays_off_the_platform_networks() {
    local service network
    [[ -f "$APPS_DOCKER_OVERLAY" ]] || return 0
    while read -r service network; do
        [[ "$service" == app-builder-docker ]] || continue
        case "$network" in
            ut-app-builder-network|proxy) ;;
            *) report "apps-docker-joins:${network}" \
                   "the App Builder's Docker joins ${network}: every app it runs reaches the services there by name" ;;
        esac
    done <<< "$(service_networks "$APPS_DOCKER_OVERLAY")"
    grep -qx ut-app-builder-network <<< "$(internal_networks "$APPS_DOCKER_OVERLAY")" \
        || report "apps-network-with-a-way-out" \
            "ut-app-builder-network is not internal: Caddy, the App Builder and the API it carries the apps to gain a way out through it"
}

check_the_apps_docker_runs_unprivileged() {
    local service profile="$REPO_ROOT/appbuilder/apparmor/ut-app-builder-docker"
    [[ -f "$APPS_DOCKER_OVERLAY" ]] || return 0
    service=$(apps_docker_service)
    grep -qE 'privileged:|cap_add:|SYS_ADMIN' <<< "$service" \
        && report "apps-docker-privileged" \
            "the App Builder's Docker is given privileges: a privileged container it starts would reach this machine's disks"
    grep -qF -- '- apparmor=ut-app-builder-docker' <<< "$service" \
        && grep -qE '^profile ut-app-builder-docker flags=\(unconfined\) \{' "$profile" 2>/dev/null \
        && grep -qE '^[[:space:]]*userns,$' "$profile" && return 0
    report "apps-docker-without-its-profile" \
        "the App Builder's Docker does not run under appbuilder/apparmor/ut-app-builder-docker, the profile that grants it a user namespace: on Ubuntu 24.04 it does not start"
}

# The uid, its range and the database owner it implies are written in four
# places that never see each other run.
check_the_apps_docker_ids_agree() {
    local uid start mongo expected
    uid=$(sed -n 's/^APP_BUILDER_DOCKER_UID=//p' "$APPS_DOCKER_SETUP")
    start=$(sed -n 's/^APP_BUILDER_DOCKER_SUBIDS_START=//p' "$APPS_DOCKER_SETUP")
    [[ -n "$uid" && -n "$start" ]] || { report "apps-docker-ids-unknown" "bin/ut-install.d/app-builder-docker.sh no longer says which uid and range the App Builder's Docker runs as"; return 0; }
    mongo=$(( start + 998 ))
    for expected in "user: \"${uid}:${uid}\"" "uid=${uid},gid=${uid}" "chown ${uid}:${uid}" \
        "APPS_MONGO_UID:-${mongo}}" "APPS_MONGO_GID:-${mongo}}"; do
        grep -qF "$expected" "$APPS_DOCKER_OVERLAY" && continue
        report "apps-docker-ids-disagree:${expected//[^A-Za-z0-9_=:-]/}" \
            "compose.appbuilder-nested.yaml lacks '${expected}', which the uid ${uid} and the range from ${start} in bin/ut-install.d/app-builder-docker.sh imply: the daemon or the apps' databases would not open their own files"
    done
}

