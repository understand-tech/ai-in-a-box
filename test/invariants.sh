# A model is served by one of its variants, NIM or vLLM, each pinned by digest: the
# same entry must start the same engine on every box.
entry_value() { sed -n "s/^$2=\"\{0,1\}\([^\"]*\)\"\{0,1\}\$/\1/p" "$1"; }

